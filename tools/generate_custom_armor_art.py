def textured_patch(a, u, v, colors, seed):
    shine, base, dark, highlight = colors
    for y in range(48):
        for x in range(48):
            # Larger coherent regions of color: plate and fabric surfaces should
            # NOT look like television static or an ore texture when worn.
            n=((x//6)*7+(y//7)*11+seed*3)%53
            c=base
            if n < 5: c=dark
            elif n > 49: c=shine
            # Gentle top-left lighting and lower-right bevel.
            if y in (2,3) and 3 < x < 43: c=shine
            if x in (2,3) and 3 < y < 40: c=shine
            if y in (44,45) or x in (44,45): c=dark
            # Sparse intentional metal engraving, never random per-pixel salt.
            if (x%17 in (0,1) and 7 < y < 35 and (x+y)%4<2):
                c=dark
            if (y%19 == 0 and 7 < x < 38 and x%4<2):
                c=shine
            if x in (0,1,46,47) or y in (0,1,46,47):
                c=dark
            a.put(u+x,v+y,c)
    # Borders and scattered rivets, fully inside each patch.
    for x in (4,23,41):
        a.rect(u+x,v+4,u+x+2,v+6,highlight)
        a.rect(u+x,v+40,u+x+2,v+42,dark)
    for x,y in ((8,14),(35,25),(18,33)):
        a.put(u+x,v+y,shine)
        a.put(u+x+1,v+y+1,highlight)

def build_atlas(name):
    a=Art(256,128)
    p=THEMES[name]
    for row,keys in ((0,("plate","shadow","gold","accent","void")),
                     (64,("light","fabric","detail","face","glow"))):
        for index,key in enumerate(keys):
            textured_patch(a,index*48,row,p[key],index+row+len(name))

    if name == "umbracita":
        # Woven folds, stitched borders and a warm brown strap. This is
        # painted into the prebuilt atlas, not a runtime effect or shader.
        u,v=48,64
        for x in (8,18,29,40):
            a.line(u+x,v+5,u+x-2,v+40,p["fabric"][2])
            a.line(u+x+2,v+6,u+x,v+40,p["fabric"][0])
        for y in (9,24,37):
            for x in range(8,43,4):
                a.put(u+x,v+y,p["fabric"][3])
        # Dark violet cloth at the chest, with broad seams rather than ore noise.
        for x in (8,26,41):
            a.line(x,68,x-2,101,p["light"][1])
            a.line(x+2,69,x,99,p["light"][0])
        # Diagonal leather stitch detail inside the brown strap patch.
        u,v=96,64
        for y in range(7,44,6):
            for x in (12,26,39):
                a.line(u+x,v+y,u+x+2,v+y+2,p["detail"][3])
        # A few polished warm studs for the medallions, nothing emissive.
        u,v=144,0
        for x,y in ((9,12),(24,19),(35,32)):
            a.rect(u+x,v+y,u+x+3,v+y+2,p["accent"][3])

    elif name == "brumacero":
        # Polished forged steel: directional sheen, restrained engraving,
        # subtle panel seams, hand-forged brass edging. No sparkle particles.
        u,v=0,0
        for x in (9,22,36):
            a.line(u+x,v+8,u+x-2,v+35,p["plate"][2],1)
            a.line(u+x+2,v+8,u+x,v+35,p["plate"][0],1)
        for y in (13,27,39):
            a.line(u+5,v+y,u+42,v+y,p["plate"][2],1)
            a.line(u+6,v+y+1,u+40,v+y+1,p["plate"][0],1)
        u,v=0,64
        for x in (9,24,39):
            a.line(u+x,v+7,u+x-2,v+39,p["light"][1],1)
            a.line(u+x+2,v+7,u+x,v+39,p["light"][3],1)
        # Gold edges on separate plates; tiny red heraldic inlays.
        u,v=96,0
        for y in (9,23,37):
            a.line(u+7,v+y,u+40,v+y,p["gold"][2],1)
            a.line(u+8,v+y+1,u+39,v+y+1,p["gold"][3],1)
        u,v=144,0
        for x,y in ((10,12),(26,15),(18,31)):
            a.rect(u+x,v+y,u+x+3,v+y+4,p["accent"][1])
            a.put(u+x+1,v+y,p["accent"][3])
        # Soft textile weaving reserved for the short ivory tabard.
        u,v=48,64
        for x in (10,20,30,41):
            a.line(u+x,v+8,u+x-1,v+37,p["fabric"][1],1)
        for y in (9,23,38):
            a.line(u+7,v+y,u+42,v+y,p["fabric"][0],1)

    for layer in (1,2):
        a.png(ASSETS/"models"/"armor"/f"{name}_layer_{layer}.png")

